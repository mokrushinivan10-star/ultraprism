function theme(
  partial: Pick<UltraTheme, "id" | "name" | "colors"> &
    Partial<Omit<UltraTheme, "id" | "name" | "colors" | "version" | "builtIn">>,
): UltraTheme {
  return {
    version: 1,
    builtIn: true,
    radius: 12,
    density: "cozy",
    blur: 14,
    glass: 78,
    font: "manrope",
    sidebar: "left",
    sidebarMode: "full",
    cards: "grid",
    cardStyle: "flat",
    motion: "subtle",
    background: "mesh",
    gradientAngle: 150,
    image: null,
    chrome: defaultChrome(),
    customCss: "",
    ...partial,
  }
}

